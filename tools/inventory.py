"""inventory.py [samples_dir] : walk samples/, dedupe by SHA-256, one row per unique save file.
Console output may show local paths. The CSV goes to work/ (git-ignored). Anything you COMMIT must use the anonymous labels
(player A, B, ...), never uploader folder names or raw user IDs: this script prints only a short hash of the ID.
Label mapping is generated into work/labels.json (git-ignored)."""
import sys, os, glob, hashlib, json, struct, datetime, csv, collections, re
sys.path.insert(0, os.path.dirname(__file__))
import keys, ff2save as F, savejson as S

ROOT = os.path.join(os.path.dirname(__file__), "..")
_args = [a for a in sys.argv[1:] if not a.startswith("--")]
SAMPLES = _args[0] if _args else os.path.join(ROOT, "samples")

def uid_tag(uid): return f"{hashlib.sha256(str(uid).encode()).hexdigest()[:6]}/{len(str(uid))}d"

def find_files():
    out = []
    for dp, dn, fn in os.walk(SAMPLES):
        dn[:] = [d for d in dn if d != "__MACOSX"]
        for f in fn:
            if f.endswith(".BIN") and not f.startswith("._"): out.append(os.path.join(dp, f))
    return sorted(out)

def labels_for(files):
    tops = sorted({os.path.relpath(f, SAMPLES).split(os.sep)[0] for f in files} - {"mine"})
    m = {"mine": "me"}; m.update({t: "player " + chr(ord("A") + i) for i, t in enumerate(tops)})
    os.makedirs(os.path.join(ROOT, "work"), exist_ok=True); json.dump(m, open(os.path.join(ROOT, "work", "labels.json"), "w"), indent=1)
    return m

def set_tag(rel):
    r = rel.lower()
    for k, v in (("nightmare practice", "nm-practice"), ("ng+practice", "ngp-practice"), ("new game save file fix", "newgame-fix"), ("all unlocked", "all-unlocked")):
        if k in r: return v
    return ""

def slot_of(path):
    p = os.path.dirname(path); b = os.path.basename(p)
    if b == "Save File": return "SAVEDATA(1)"   # a single save shipped without a slot folder
    return b.split(" - ")[0] if b.startswith("SYSTEM") else b

def write_md(rows, files, lab, by_sha):
    """Anonymized, committable summary: letters instead of uploaders, ID *groups* instead of IDs, no hashes of IDs."""
    groups = {}
    for r in rows: groups.setdefault(r["uid"], f"ID-{chr(ord('a') + len(groups))} ({r['uid_digits']} digits)")
    rt = {}
    rtf = os.path.join(ROOT, "work", "roundtrip_all.txt")
    if os.path.exists(rtf):
        for line in open(rtf):
            m = re.match(r"ROUNDTRIP OK\s+(.*?)\s+\(decrypt", line)   # paths may contain spaces
            if m: rt[m.group(1)] = True
    per = collections.defaultdict(lambda: [0, 0, 0])
    for f in files:
        l = lab[os.path.relpath(f, SAMPLES).split(os.sep)[0]]; per[l][0] += 1; per[l][1] += 1 if os.path.abspath(f) in {os.path.abspath(k) for k in rt} else 0
        per[l][2] += 1 if os.path.getsize(f) == 61851984 else 0
    L = ["# Sample inventory (anonymized, generated by `tools/inventory.py --md`)", "",
         "Sources are labelled player A, B, ... in alphabetical order of the (private) uploader folder names; `me` = the repo owner. Set tags (`ngp-practice`, `nm-practice`, ...) and the uploaders' names for what a save is are **hints, not proof**. User IDs appear only as groups (equal ID = same group). The label mapping lives in git-ignored `work/labels.json`.", "",
         f"Files found: {len(files)}; unique by SHA-256: {len(rows)}. All unique files decrypt and verify; see 'round trip' below.", "",
         "| source | set | slot | file(s) | chapter | progress | saved (UTC) | play h | lap | SAVEDATA vs BACKUP | user-ID group | sha |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['label']} | {r['set'] or '-'} | {r['slot']} | {r['kind']} | {r['chapter']} | {r['progress']} | {r['ts_s']} | {r['play_h']} | {r['lap']} | {r['relation']} | {groups[r['uid']]} | {r['sha']} |")
    L += ["", "## Round trip (C# `ff2rsave verify --roundtrip`, all files on disk, duplicates included)", "", "| source | files | system saves | round-trip byte-identical |", "|---|---|---|---|"]
    for l, (n, ok, sy) in sorted(per.items()): L.append(f"| {l} | {n} | {sy} | {ok}/{n} |")
    open(os.path.join(ROOT, "docs", "sample_inventory.md"), "w").write("\n".join(L) + "\n")

def main():
    cfg = keys.load(); files = find_files(); lab = labels_for(files)
    by_sha = collections.OrderedDict()
    for f in files:
        h = hashlib.sha256(open(f, "rb").read()).hexdigest(); by_sha.setdefault(h, []).append(f)
    rows = []; notes = []
    for sha, paths in by_sha.items():
        f = paths[0]; rel = os.path.relpath(f, SAMPLES); parts = rel.split(os.sep); L = lab[parts[0]]
        raw = open(f, "rb").read(); hdr, pt = F.decrypt(raw, cfg); magic = hdr[:8].rstrip(b"\0").decode(errors="replace")
        u = lambda o, w=4: int.from_bytes(hdr[o:o+w], "little")
        problems = F.verify(raw, cfg)
        lap = progress_json = "-"
        try:
            _, _, obj, _ = S.load(f, cfg)
            if magic == "WLNUSR": lap = obj["MissionData"]["lap_num"]; progress_json = obj["MissionData"]["main_mission_progress"]
        except Exception as e: notes.append(f"JSON load failed for {L}/{slot_of(f)}: {e}")
        names = {os.path.basename(x) for x in paths if os.path.dirname(x) == os.path.dirname(f)}
        kind = "system" if magic == "WLNSYS" else ("SAVEDATA=BACKUP" if names >= {"SAVEDATA.BIN", "BACKUP.BIN"} else ("BACKUP" if os.path.basename(f) == "BACKUP.BIN" else "SAVEDATA"))
        ts = u(0x30, 8); pt_us = u(0x28, 8)
        also = [lab[os.path.relpath(p, SAMPLES).split(os.sep)[0]] + "/" + set_tag(os.path.relpath(p, SAMPLES)) + "/" + slot_of(p) for p in paths[1:]]
        rows.append(dict(sha=sha[:8], label=L, set=set_tag(rel), slot=slot_of(f), kind=kind, magic=magic, size=len(raw), uid=uid_tag(u(0x10)), uid_digits=len(str(u(0x10))), chapter=u(0x20) if magic == "WLNUSR" else "-",
                         progress=u(0x24) if magic == "WLNUSR" else "-", ts=ts, ts_s=datetime.datetime.fromtimestamp(ts, datetime.UTC).strftime("%Y-%m-%d %H:%M") if ts else "-",
                         play_h=round(pt_us / 3.6e9, 2) if magic == "WLNUSR" else "-", lap=lap, loader_problems="; ".join(problems) or "ok", also="; ".join(also), progress_json_matches_hdr=(progress_json == u(0x24)) if magic == "WLNUSR" else "-",
                         _ts=ts, _pt=pt_us, _dir=os.path.dirname(f), _src=f))
    # SAVEDATA vs BACKUP relation per slot directory
    rel = {}
    byd = collections.defaultdict(dict)
    for r in rows: byd[r["_dir"]][r["kind"]] = r
    for p in files:  # include files deduped away (e.g. identical BACKUP == SAVEDATA content in same dir)
        pass
    for d, kinds in byd.items(): pass
    # recompute using all files (dedupe may hide an identical BACKUP)
    dirs = collections.defaultdict(dict)
    for f in files: dirs[os.path.dirname(f)][os.path.basename(f)] = f
    for d, fs in dirs.items():
        if "SAVEDATA.BIN" not in fs: continue
        if "BACKUP.BIN" not in fs: rel[d] = "BACKUP missing"; continue
        a = open(fs["SAVEDATA.BIN"], "rb").read(); b = open(fs["BACKUP.BIN"], "rb").read()
        if a == b: rel[d] = "identical"; continue
        ha = (int.from_bytes(a[0x30:0x38], "little"), int.from_bytes(a[0x28:0x30], "little")); hb = (int.from_bytes(b[0x30:0x38], "little"), int.from_bytes(b[0x28:0x30], "little"))
        rel[d] = "BACKUP older" if hb < ha else ("BACKUP newer" if hb > ha else "differs (same ts/playtime)")
    for r in rows: r["relation"] = rel.get(r["_dir"], "n/a (system)" if r["kind"] == "system" else "?")
    cols = ["label", "set", "slot", "kind", "magic", "size", "uid", "chapter", "progress", "ts_s", "play_h", "lap", "relation", "loader_problems", "sha", "also"]
    w = {c: max(len(str(r[c])) for r in rows + [{c: c}]) for c in cols}
    print(" | ".join(c.ljust(w[c]) for c in cols)); print("-+-".join("-" * w[c] for c in cols))
    for r in rows: print(" | ".join(str(r[c]).ljust(w[c]) for c in cols))
    with open(os.path.join(ROOT, "work", "inventory.csv"), "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=cols + ["progress_json_matches_hdr"], extrasaction="ignore"); wr.writeheader(); wr.writerows(rows)
    if "--md" in sys.argv: write_md(rows, files, lab, by_sha)
    print(f"\nfiles on disk: {len(files)}; unique by SHA-256: {len(rows)}; duplicates removed: {len(files) - len(rows)}")
    for n in notes: print("NOTE:", n)

if __name__ == "__main__": main()
